'use strict';

const fs = require('fs');
const path = require('path');
const { pickLanIPv4 } = require('./lan-ipv4.cjs');

const host = pickLanIPv4();
const dest = path.join(__dirname, '..', 'src', 'environments', 'lan-host.ts');
const body = `/** Auto-generated by scripts/write-lan-host.cjs. Override: DEV_LAN_HOST=x.x.x.x */
export const LAN_HOST = '${host}';
`;

fs.writeFileSync(dest, body, 'utf8');
console.log(`[android] LAN API host: ${host} (phone must be on the same Wi‑Fi)`);
